const GRATITUDE_MIXED = Object.freeze([...GRATITUDE_POOLS.normal, ...GRATITUDE_POOLS.soft, ...GRATITUDE_POOLS.edgy]);
const gratitudeDecks = new Map();
function drawGratitudeIndex(poolName = "mixed") {
  const pool = poolName === "mixed" ? GRATITUDE_MIXED : GRATITUDE_POOLS[poolName];
  if (!pool) throw new Error("Unknown gratitude personality");
  let deck = gratitudeDecks.get(poolName);
  if (!deck || !deck.length) {
    deck = Array.from({length:pool.length}, (_,i) => i);
    for (let i=deck.length-1; i>0; i--) {
      const j=Math.floor(Math.random()*(i+1));
      [deck[i],deck[j]]=[deck[j],deck[i]];
    }
    gratitudeDecks.set(poolName,deck);
  }
  return deck.pop();
}
// Global script is loaded before the Lounge module; immutable data is exposed only.
window.WildLedgerGratitude = Object.freeze({pools:GRATITUDE_POOLS,mixed:GRATITUDE_MIXED,drawIndex:drawGratitudeIndex});
